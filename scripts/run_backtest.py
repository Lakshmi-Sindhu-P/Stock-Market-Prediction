#!/usr/bin/env python
"""Run the walk-forward backtest, save artifacts, and regenerate reports/RESULTS.md.

Usage:
    python scripts/run_backtest.py [--models persistence,drift,ridge,lstm]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from spx_forecast import config  # noqa: E402
from spx_forecast.backtest import run_backtest  # noqa: E402
from spx_forecast.data import load_raw  # noqa: E402
from spx_forecast.features import build_features  # noqa: E402
from spx_forecast.models import default_factories  # noqa: E402
from spx_forecast.plots import plot_all  # noqa: E402


def _fmt(v, digits=2, dash="—"):
    if v is None:
        return dash
    return f"{v:.{digits}f}"


def write_report(metrics: dict, figures: list[str]) -> Path:
    meta = metrics["_meta"]
    order = [m for m in ("persistence", "drift", "ridge", "lstm") if m in metrics]
    best = min(order, key=lambda m: metrics[m]["mae_bp"])

    rows = []
    for m in order:
        d = metrics[m]
        dm = d.get("dm_vs_naive") or {}
        rows.append(
            f"| {m} | {_fmt(d['rmse_bp'])} | {_fmt(d['mae_bp'])} | "
            f"{_fmt(d['mase'], 4)} | {_fmt(d['r2'], 4)} | "
            f"{_fmt(d['direction_acc'], 3)} | "
            f"{_fmt(dm.get('stat'), 2)} | {_fmt(dm.get('p_value'), 3)} |"
        )
    table = ("| model | RMSE (bp) | MAE (bp) | MASE | R² | hit rate | DM stat | DM p |\n"
             "|---|---|---|---|---|---|---|---|\n" + "\n".join(rows))

    lstm = metrics.get("lstm", {})
    dm_p = (lstm.get("dm_vs_naive") or {}).get("p_value")
    verdict = ("no statistically distinguishable edge over the naive forecast"
               if dm_p is None or dm_p > 0.05
               else "a statistically distinguishable difference from the naive forecast")

    rel = {p: Path(p).relative_to(ROOT).as_posix() for p in figures if p}
    figs = "\n\n".join(f"![{Path(p).stem}]({rel[p]})" for p in figures) if figures else ""

    body = f"""# Results

Generated by `scripts/run_backtest.py` — do not edit by hand.

Out-of-sample window **{meta['test_start']} → {meta['test_end']}**
({meta['test_rows']} trading days, {len(meta['folds'])} walk-forward folds,
refit every {meta['refit_every']} days).

## Metrics (next-day log-return space)

{table}

Losses are in basis points of daily log return (1 bp = 0.01%). MASE is relative
to the persistence forecast: **< 1 beats "tomorrow = today", > 1 is worse**.
Hit rate is the share of days with the correct sign. DM is the Diebold–Mariano
statistic against persistence (positive = worse than naive).

Best model by MAE: **{best}**.

## Verdict

The LSTM shows {verdict} (Newey–West DM p = {_fmt(dm_p, 3)}). Predicted returns
also have far smaller dispersion than realised ones
(the network regresses toward the mean), which is the expected behaviour when
next-day index returns are close to unpredictable.

## Figures

{figs}
"""
    path = ROOT / "reports" / "RESULTS.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body)
    return path


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", default="persistence,drift,ridge,lstm",
                    help="comma-separated subset of: persistence,drift,ridge,lstm")
    args = ap.parse_args()

    wanted = [m.strip() for m in args.models.split(",") if m.strip()]
    factories = {k: v for k, v in default_factories().items() if k in wanted}
    if not factories:
        raise SystemExit(f"no known models in {wanted}")

    frame = build_features(load_raw())
    print(f"features: {frame.shape[0]} rows  {frame.index[0].date()} → {frame.index[-1].date()}")

    result = run_backtest(frame, factories)
    config.PREDICTIONS_CSV.parent.mkdir(parents=True, exist_ok=True)
    result.predictions.to_csv(config.PREDICTIONS_CSV, float_format="%.8f")
    config.METRICS_JSON.write_text(json.dumps(result.metrics, indent=2) + "\n")

    figures = plot_all(result.predictions, result.metrics)
    report = write_report(result.metrics, figures)

    print(f"\n{'model':12s} {'RMSE bp':>8s} {'MAE bp':>8s} {'MASE':>7s} {'hit':>6s}")
    for name, m in result.metrics.items():
        if name.startswith("_"):
            continue
        print(f"{name:12s} {m['rmse_bp']:8.2f} {m['mae_bp']:8.2f} "
              f"{m['mase']:7.4f} {_fmt(m['direction_acc'], 3):>6s}")
    print(f"\nwrote {config.PREDICTIONS_CSV.relative_to(ROOT)}, "
          f"{config.METRICS_JSON.relative_to(ROOT)}, {report.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
